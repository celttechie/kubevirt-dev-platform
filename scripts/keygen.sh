#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"

KEYS_DIR="${REPO_ROOT}/substrate/keys"
LOCAL_SSH_DIR="${REPO_ROOT}/.ssh"

VM_IP="${VM_IP:-192.168.122.50}"
VM_HOSTNAME="${VM_HOSTNAME:-kubevirt-sandbox-vm}"
ADMIN_USER="${ADMIN_USER:-admin}"
JUMP_HOST="${JUMP_HOST:-}"

# Check substrate/terraform.tfvars for local developer overrides
if [[ -f "${REPO_ROOT}/substrate/terraform.tfvars" ]]; then
  DETECTED_IP="$(grep -E '^\s*vm_ip\s*=' "${REPO_ROOT}/substrate/terraform.tfvars" | sed -E 's/.*=\s*"([^"]+)".*/\1/' || true)"
  if [[ -n "${DETECTED_IP}" ]]; then
    VM_IP="${DETECTED_IP}"
  fi
  DETECTED_USER="$(grep -E '^\s*admin_username\s*=' "${REPO_ROOT}/substrate/terraform.tfvars" | sed -E 's/.*=\s*"([^"]+)".*/\1/' || true)"
  if [[ -n "${DETECTED_USER}" ]]; then
    ADMIN_USER="${DETECTED_USER}"
  fi
fi

mkdir -p "${KEYS_DIR}" "${LOCAL_SSH_DIR}"
chmod 700 "${KEYS_DIR}" "${LOCAL_SSH_DIR}"

CLIENT_KEY="${KEYS_DIR}/id_kubevirt_dev_ed25519"
CLIENT_PUB="${CLIENT_KEY}.pub"

HOST_KEY="${KEYS_DIR}/ssh_host_ed25519_key"
HOST_PUB="${HOST_KEY}.pub"

KNOWN_HOSTS="${LOCAL_SSH_DIR}/known_hosts"
SSH_CONFIG="${LOCAL_SSH_DIR}/config"

echo "==> Ensuring deterministic SSH keys..."

# 1. Generate client keypair if not present
if [[ ! -f "${CLIENT_KEY}" ]]; then
  echo "    Generating client ED25519 keypair..."
  ssh-keygen -t ed25519 -N "" -C "${ADMIN_USER}@kubevirt-dev-platform" -f "${CLIENT_KEY}"
  chmod 600 "${CLIENT_KEY}"
  chmod 644 "${CLIENT_PUB}"
else
  echo "    Client keypair already exists: ${CLIENT_KEY}"
fi

# 2. Generate host keypair if not present
if [[ ! -f "${HOST_KEY}" ]]; then
  echo "    Generating deterministic VM host ED25519 keypair..."
  ssh-keygen -t ed25519 -N "" -C "${VM_HOSTNAME}-host-key" -f "${HOST_KEY}"
  chmod 600 "${HOST_KEY}"
  chmod 644 "${HOST_PUB}"
else
  echo "    Host keypair already exists: ${HOST_KEY}"
fi

# Mirror keys into .ssh/ for convenience
cp -f "${CLIENT_KEY}" "${LOCAL_SSH_DIR}/"
cp -f "${CLIENT_PUB}" "${LOCAL_SSH_DIR}/"

# 3. Generate deterministic known_hosts entry
HOST_PUB_CONTENT="$(awk '{print $1 " " $2}' "${HOST_PUB}")"

echo "    Generating deterministic known_hosts entry for ${VM_IP} and ${VM_HOSTNAME}..."
{
  echo "${VM_IP} ${HOST_PUB_CONTENT}"
  echo "${VM_HOSTNAME} ${HOST_PUB_CONTENT}"
  echo "${VM_HOSTNAME}.sandbox.local ${HOST_PUB_CONTENT}"
} > "${KNOWN_HOSTS}"
chmod 644 "${KNOWN_HOSTS}"

# 4. Generate local SSH config
PROXY_JUMP_LINE=""
if [[ -n "${JUMP_HOST}" ]]; then
  PROXY_JUMP_LINE="    ProxyJump ${JUMP_HOST}"
fi

cat <<EOF > "${SSH_CONFIG}"
# Generated by scripts/keygen.sh - Strict Host Key Checking Enforced
Host kubevirt-sandbox
    HostName ${VM_IP}
    User ${ADMIN_USER}
${PROXY_JUMP_LINE}
    IdentityFile ${LOCAL_SSH_DIR}/id_kubevirt_dev_ed25519
    IdentitiesOnly yes
    UserKnownHostsFile ${KNOWN_HOSTS}
    StrictHostKeyChecking yes
    CheckHostIP yes
    ConnectTimeout 10
EOF
chmod 600 "${SSH_CONFIG}"

echo "==> Deterministic SSH setup complete!"
echo "    Known hosts: ${KNOWN_HOSTS}"
echo "    SSH Config:  ${SSH_CONFIG}"
echo "    Client Pub:  $(cat "${CLIENT_PUB}")"
echo "    Host Pub:    $(cat "${HOST_PUB}")"
